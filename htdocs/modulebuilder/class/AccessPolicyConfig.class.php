/**
 * Immutable access policy of the pages generated by ModuleBuilder: a rule tree and a deny message.
 *
 * The rule tree is an array made of 'and' and 'or' nodes ({type, rules}) whose leaves are whitelisted
 * 'predicate' nodes ({type, name}): there is no way to inject a free PHP expression in the generated pages.
 * A policy is always valid once built: every way in (constructor, fromJson(), fromAlternatives())
 * rejects an unknown node, an unknown predicate, a tree out of bounds or a message that is not a
 * translation key.
 */
final class AccessPolicyConfig
{
	const MAX_DEPTH = 4;
	const MAX_NODES = 32;
	const MAX_ALTERNATIVES = 3;
	const MAX_MESSAGE_LENGTH = 128;

	/** Types of the nodes of the rule tree */
	const NODE_PREDICATE = 'predicate';
	const NODE_AND = 'and';
	const NODE_OR = 'or';

	/**
	 * PHP rendered for each whitelisted predicate. The mymodule and myobject tokens are replaced by the
	 * generator with the names of the generated module and object.
	 */
	const PREDICATES = array(
		'isAdmin' => '!empty($user->admin)',
		'isInternalUser' => 'empty($user->socid)',
		'canReadObject' => "\$user->hasRight('mymodule', 'myobject', 'read')",
		'canWriteObject' => "\$user->hasRight('mymodule', 'myobject', 'write')",
		'canDeleteObject' => "\$user->hasRight('mymodule', 'myobject', 'delete')",
	);

	/** @var array<string,mixed> Root of the rule tree, normalized */
	private $expression;

	/** @var string Translation key passed to accessforbidden(), empty for the default message */
	private $message;

	/**
	 * @param	array<string,mixed>	$expression	Root of the rule tree
	 * @param	string				$message	Translation key shown on deny, empty for the default message
	 * @throws	\InvalidArgumentException	When the tree is invalid or out of bounds, or the message is not a translation key
	 */
	public function __construct(array $expression, string $message = '')
	{
		if (strlen($message) > self::MAX_MESSAGE_LENGTH || !preg_match('/^[A-Za-z0-9_]*$/D', $message)) {
			throw new \InvalidArgumentException('The access policy message must be a translation key');
		}
		$nodecount = 0;

		$this->expression = self::normalizeNode($expression, 1, $nodecount);
		$this->message = $message;
	}

	/**
	 * Build a policy from the editor of ModuleBuilder: the predicates of an alternative are combined
	 * with AND, the alternatives with OR. Empty alternatives are ignored.
	 *
	 * @param	array<int,string[]>	$alternatives	List of alternatives, each one a list of predicate names
	 * @param	string				$message		Translation key shown on deny
	 * @return	AccessPolicyConfig|null				Null when no predicate is selected at all
	 * @throws	\InvalidArgumentException			When there are too many alternatives or a predicate is unknown
	 */
	public static function fromAlternatives(array $alternatives, string $message = ''): ?self
	{
		if (count($alternatives) > self::MAX_ALTERNATIVES) {
			throw new \InvalidArgumentException('An access policy accepts at most '.self::MAX_ALTERNATIVES.' alternatives');
		}

		$rules = array();
		foreach ($alternatives as $alternative) {
			if (!is_array($alternative)) {
				throw new \InvalidArgumentException('An access policy alternative must be a list of predicates');
			}
			if (empty($alternative)) {
				continue;
			}
			$predicates = array();
			foreach (array_values(array_unique($alternative, SORT_REGULAR)) as $name) {
				if (!is_string($name)) {
					throw new \InvalidArgumentException('An access policy predicate name must be a string');
				}
				$predicates[] = array('type' => self::NODE_PREDICATE, 'name' => $name);
			}
			$rules[] = (count($predicates) == 1) ? $predicates[0] : array('type' => self::NODE_AND, 'rules' => $predicates);
		}

		if (empty($rules)) {
			return null;
		}
		return new self((count($rules) == 1) ? $rules[0] : array('type' => self::NODE_OR, 'rules' => $rules), $message);
	}

	/**
	 * Load a serialized policy, as produced by toJson().
	 *
	 * @param	string	$json	Serialized policy
	 * @return	AccessPolicyConfig			The loaded policy
	 * @throws	\InvalidArgumentException	When the content is not a valid policy
	 */
	public static function fromJson(string $json): self
	{
		$data = json_decode($json, true);
		if (!is_array($data) || json_last_error() !== JSON_ERROR_NONE) {
			throw new \InvalidArgumentException('The serialized access policy is not a JSON object');
		}
		if (!isset($data['expression']) || !is_array($data['expression'])) {
			throw new \InvalidArgumentException('The serialized access policy has no expression');
		}
		$message = isset($data['message']) ? $data['message'] : '';
		if (!is_string($message)) {
			throw new \InvalidArgumentException('The access policy message must be a translation key');
		}

		return new self($data['expression'], $message);
	}

	/**
	 * Serialize the policy. The order of the rules is kept, so the output is deterministic.
	 *
	 * @return string	Serialized policy, in JSON
	 */
	public function toJson(): string
	{
		return (string) json_encode(array('expression' => $this->expression, 'message' => $this->message), JSON_UNESCAPED_SLASHES);
	}

	/**
	 * Render the rule tree as a PHP boolean expression, composite nodes being wrapped in parentheses.
	 *
	 * @return string	PHP boolean expression
	 */
	public function toPhp(): string
	{
		return self::nodeToPhp($this->expression);
	}

	/**
	 * @return array<string,mixed>	Root of the rule tree
	 */
	public function getExpression(): array
	{
		return $this->expression;
	}

	/**
	 * @return string	Translation key shown on deny, empty for the default message
	 */
	public function getMessage(): string
	{
		return $this->message;
	}

	/**
	 * Render a node of the tree as a PHP boolean expression. OR is rendered with ||, never with the
	 * `or` keyword which binds looser than `=`.
	 *
	 * @param	array<string,mixed>	$node	Normalized node
	 * @return	string						PHP boolean expression
	 */
	private static function nodeToPhp(array $node): string
	{
		if ($node['type'] === self::NODE_PREDICATE) {
			return self::PREDICATES[$node['name']];
		}

		$parts = array();
		foreach ($node['rules'] as $child) {
			$parts[] = self::nodeToPhp($child);
		}
		return '('.implode(($node['type'] === self::NODE_AND ? ' && ' : ' || '), $parts).')';
	}

	/**
	 * Check a node of the tree and return it with only its known keys, so it serializes deterministically.
	 *
	 * @param	mixed	$data		Node to check
	 * @param	int		$depth		Depth of the node, 1 for the root
	 * @param	int		$nodecount	Number of nodes met so far, updated
	 * @return	array<string,mixed>			The normalized node
	 * @throws	\InvalidArgumentException	When the node is invalid or the tree is out of bounds
	 */
	private static function normalizeNode($data, int $depth, int &$nodecount): array
	{
		$nodecount++;
		if ($depth > self::MAX_DEPTH) {
			throw new \InvalidArgumentException('The access policy is deeper than '.self::MAX_DEPTH.' levels');
		}
		if ($nodecount > self::MAX_NODES) {
			throw new \InvalidArgumentException('The access policy has more than '.self::MAX_NODES.' nodes');
		}
		if (!is_array($data) || !isset($data['type']) || !is_string($data['type'])) {
			throw new \InvalidArgumentException('An access policy node must have a type');
		}

		if ($data['type'] === self::NODE_PREDICATE) {
			if (!isset($data['name']) || !is_string($data['name'])) {
				throw new \InvalidArgumentException('An access policy predicate must have a name');
			}
			if (!array_key_exists($data['name'], self::PREDICATES)) {
				throw new \InvalidArgumentException('Unknown access rule predicate: '.$data['name']);
			}
			return array('type' => self::NODE_PREDICATE, 'name' => $data['name']);
		}

		if ($data['type'] !== self::NODE_AND && $data['type'] !== self::NODE_OR) {
			throw new \InvalidArgumentException('Unknown access policy node type: '.$data['type']);
		}
		if (empty($data['rules']) || !is_array($data['rules'])) {
			throw new \InvalidArgumentException('An access policy '.$data['type'].' node must have a non empty list of rules');
		}
		$rules = array();
		foreach ($data['rules'] as $child) {
			$rules[] = self::normalizeNode($child, $depth + 1, $nodecount);
		}
		return array('type' => $data['type'], 'rules' => $rules);
	}
}
