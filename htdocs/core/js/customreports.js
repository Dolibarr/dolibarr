/**
 * Init the component to select measures of custom reports (HTML generated by customReportsSelectMeasures()).
 * Fields are listed first, a click on a field with variants expands the list of its variants.
 *
 * @param	{string}	componentid		Id of the div of component
 * @return	{void}
 */
function initCustomReportsMeasures(componentid)
{
	var $component = jQuery('#' + componentid);
	if (!$component.length || $component.data('initdone')) {
		return;
	}
	$component.data('initdone', 1);

	var $select = jQuery('#' + $component.data('htmlname'));
	var $control = $component.find('.customreportsmeasures-control');
	var $tags = $component.find('.customreportsmeasures-tags');
	var $placeholder = $component.find('.customreportsmeasures-placeholder');
	var $dropdown = $component.find('.customreportsmeasures-dropdown');
	var $search = $component.find('.customreportsmeasures-search');

	/* Return the option of the hidden select for a value */
	function getOption(value)
	{
		return $select.find('option').filter(function() { return this.value === value; });
	}

	/* Refresh tags, check marks and counters from the hidden select */
	function refresh()
	{
		$tags.empty();
		$component.find('.customreportsmeasures-item').each(function() {
			var $item = jQuery(this);
			var selected = getOption($item.data('value')).prop('selected') ? true : false;
			$item.toggleClass('customreportsmeasures-selected', selected);
			$item.attr('aria-selected', selected ? 'true' : 'false');
			if (selected) {
				var $tag = jQuery('<span class="marginleftonlyshort valignmiddle tagsearch"></span>');
				var $remove = jQuery('<span class="tagsearchdelete select2-selection__choice__remove customreportsmeasures-remove">x</span>').data('value', $item.data('value'));
				$tags.append($tag.append($remove, ' ', document.createTextNode($item.data('tag'))));
			}
		});
		$component.find('.customreportsmeasures-hasvariants').each(function() {
			var nb = jQuery(this).find('.customreportsmeasures-selected').length;
			jQuery(this).find('.customreportsmeasures-count').text(nb).toggleClass('hidden', nb === 0);
		});
		$placeholder.toggleClass('hidden', $tags.children().length > 0);
	}

	function toggleValue(value)
	{
		var $option = getOption(value);
		$option.prop('selected', !$option.prop('selected'));
		$select.trigger('change');
		refresh();
	}

	function openDropdown()
	{
		$dropdown.removeClass('hidden');
		$control.attr('aria-expanded', 'true');
		$search.trigger('focus');
	}

	function closeDropdown()
	{
		$dropdown.addClass('hidden');
		$control.attr('aria-expanded', 'false');
	}

	function expandField($field, expand)
	{
		$field.toggleClass('customreportsmeasures-expanded', expand);
		$field.find('.customreportsmeasures-variants').toggleClass('hidden', !expand);
		$field.find('.customreportsmeasures-expand').toggleClass('fa-caret-right', !expand).toggleClass('fa-caret-down', expand);
	}

	// Click in the zone of component (except on a tag or into the dropdown) open or close the dropdown
	$component.on('click', function(event) {
		var $target = jQuery(event.target);
		var $remove = $target.closest('.customreportsmeasures-remove');
		if ($remove.length) {
			event.stopPropagation();
			toggleValue($remove.data('value'));
			return;
		}
		if ($target.closest('.tagsearch, .customreportsmeasures-dropdown').length) {
			return;
		}
		if ($dropdown.hasClass('hidden')) {
			openDropdown();
		} else {
			closeDropdown();
		}
	});

	$control.on('keydown', function(event) {
		if (event.key === 'Enter' || event.key === ' ' || event.key === 'ArrowDown') {
			event.preventDefault();
			openDropdown();
		}
	});

	// Click on a field with variants: show or hide its variants
	$component.on('click', '.customreportsmeasures-hasvariants > .customreportsmeasures-fieldlabel', function() {
		var $field = jQuery(this).parent();
		expandField($field, !$field.hasClass('customreportsmeasures-expanded'));
	});

	// Click on a selectable entry (variant or field without variant)
	$component.on('click', '.customreportsmeasures-item', function(event) {
		event.stopPropagation();
		toggleValue(jQuery(this).data('value'));
	});

	$search.on('input', function() {
		var filter = jQuery(this).val().toLowerCase().trim();
		$component.find('.customreportsmeasures-field').each(function() {
			var $field = jQuery(this);
			$field.toggleClass('hidden', filter !== '' && String($field.data('search')).indexOf(filter) === -1);
		});
	});

	$search.on('keydown', function(event) {
		if (event.key === 'Escape') {
			closeDropdown();
			$control.trigger('focus');
		}
	});

	jQuery(document).on('click', function(event) {
		if (!jQuery(event.target).closest($component).length) {
			closeDropdown();
		}
	});

	// Expand fields that already have a selected variant
	refresh();
	$component.find('.customreportsmeasures-hasvariants').each(function() {
		if (jQuery(this).find('.customreportsmeasures-selected').length) {
			expandField(jQuery(this), true);
		}
	});
}
