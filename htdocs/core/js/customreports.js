/**
 * Move the keyboard focus on the previous (up arrow) or next (down arrow) visible row of a popup list.
 * From the search input, only the down arrow moves on the first row.
 *
 * @param	{Event}		event		Keydown event
 * @param	{jQuery}	$rows		Visible rows of the list, in their order
 * @param	{jQuery}	$search		Search input of the popup
 * @return	{boolean}				True if the event was managed
 */
function customReportsMoveFocusInList(event, $rows, $search)
{
	var isnext = (event.key === 'ArrowDown');
	var isprev = (event.key === 'ArrowUp');
	if (!isnext && !isprev) {
		return false;
	}
	var insearch = (event.target === $search[0]);
	if (insearch && event.key !== 'ArrowDown') {
		return false;
	}
	event.preventDefault();
	var index = (insearch ? -1 : $rows.index(event.target)) + (isnext ? 1 : -1);
	if (index < 0) {
		$search.trigger('focus');
	} else if (index < $rows.length) {
		$rows.eq(index).trigger('focus');
	}
	return true;
}

/**
 * Init the component to select measures of custom reports (HTML generated by customReportsSelectMeasures()).
 * Fields are listed first, a click on a field with variants expands the list of its variants.
 *
 * @param	{string}	componentid		Id of the div of component
 * @return	{void}
 */
function initCustomReportsMeasures(componentid)
{
	var $component = jQuery('#' + componentid);
	if (!$component.length || $component.data('initdone')) {
		return;
	}
	$component.data('initdone', 1);

	var $select = jQuery('#' + $component.data('htmlname'));
	var $control = $component.find('.customreportsmeasures-control');
	var $tags = $component.find('.customreportsmeasures-tags');
	var $placeholder = $component.find('.customreportsmeasures-placeholder');
	var $dropdown = $component.find('.customreportsmeasures-dropdown');
	var $search = $component.find('.customreportsmeasures-search');

	/* Return the option of the hidden select for a value */
	function getOption(value)
	{
		return $select.find('option').filter(function() { return this.value === value; });
	}

	/* Refresh tags, check marks and counters from the hidden select */
	function refresh()
	{
		$tags.empty();
		$component.find('.customreportsmeasures-item').each(function() {
			var $item = jQuery(this);
			var selected = getOption($item.data('value')).prop('selected') ? true : false;
			$item.toggleClass('customreportsmeasures-selected', selected);
			$item.attr('aria-selected', selected ? 'true' : 'false');
			if (selected) {
				var $tag = jQuery('<span class="marginleftonlyshort valignmiddle tagsearch"></span>');
				var $remove = jQuery('<span class="tagsearchdelete select2-selection__choice__remove customreportsmeasures-remove">x</span>').data('value', $item.data('value'));
				$tags.append($tag.append($remove, ' ', document.createTextNode($item.data('tag'))));
			}
		});
		$component.find('.customreportsmeasures-hasvariants').each(function() {
			var nb = jQuery(this).find('.customreportsmeasures-selected').length;
			jQuery(this).find('.customreportsmeasures-count').text(nb).toggleClass('hidden', nb === 0);
		});
		$placeholder.toggleClass('hidden', $tags.children().length > 0);
	}

	function toggleValue(value)
	{
		var $option = getOption(value);
		$option.prop('selected', !$option.prop('selected'));
		$select.trigger('change');
		refresh();
	}

	function openDropdown()
	{
		$dropdown.removeClass('hidden');
		$control.attr('aria-expanded', 'true');
		$search.trigger('focus');
	}

	function closeDropdown()
	{
		$dropdown.addClass('hidden');
		$control.attr('aria-expanded', 'false');
	}

	function expandField($field, expand)
	{
		$field.toggleClass('customreportsmeasures-expanded', expand);
		$field.find('.customreportsmeasures-variants').toggleClass('hidden', !expand);
		$field.find('.customreportsmeasures-expand').toggleClass('fa-caret-right', !expand).toggleClass('fa-caret-down', expand);
	}

	// Click in the zone of component (except on a tag or into the dropdown) open or close the dropdown
	$component.on('click', function(event) {
		var $target = jQuery(event.target);
		var $remove = $target.closest('.customreportsmeasures-remove');
		if ($remove.length) {
			event.stopPropagation();
			toggleValue($remove.data('value'));
			return;
		}
		if ($target.closest('.tagsearch, .customreportsmeasures-dropdown').length) {
			return;
		}
		if ($dropdown.hasClass('hidden')) {
			openDropdown();
		} else {
			closeDropdown();
		}
	});

	$control.on('keydown', function(event) {
		if (event.key === 'Enter' || event.key === ' ' || event.key === 'ArrowDown' || event.key === 'ArrowRight') {
			event.preventDefault();
			openDropdown();
		}
	});

	// Keyboard into the dropdown: up and down arrows move on the previous or next row, Enter or Space activates the row, Escape closes
	$component.find('.customreportsmeasures-fieldlabel, .customreportsmeasures-variants .customreportsmeasures-item').attr('tabindex', '-1');
	$dropdown.on('keydown', function(event) {
		var $rows = $component.find('.customreportsmeasures-fieldlabel:visible, .customreportsmeasures-variants .customreportsmeasures-item:visible');
		if (customReportsMoveFocusInList(event, $rows, $search)) {
			return;
		}
		if (event.target !== $search[0] && (event.key === 'Enter' || event.key === ' ')) {
			event.preventDefault();
			jQuery(event.target).trigger('click');
		} else if (event.target !== $search[0] && event.key === 'Escape') {
			closeDropdown();
			$control.trigger('focus');
		}
	});

	// Click on a field with variants: show or hide its variants
	$component.on('click', '.customreportsmeasures-hasvariants > .customreportsmeasures-fieldlabel', function() {
		var $field = jQuery(this).parent();
		expandField($field, !$field.hasClass('customreportsmeasures-expanded'));
	});

	// Click on a selectable entry (variant or field without variant)
	$component.on('click', '.customreportsmeasures-item', function(event) {
		event.stopPropagation();
		toggleValue(jQuery(this).data('value'));
	});

	$search.on('input', function() {
		var filter = jQuery(this).val().toLowerCase().trim();
		$component.find('.customreportsmeasures-field').each(function() {
			var $field = jQuery(this);
			$field.toggleClass('hidden', filter !== '' && String($field.data('search')).indexOf(filter) === -1);
		});
	});

	$search.on('keydown', function(event) {
		if (event.key === 'Escape') {
			closeDropdown();
			$control.trigger('focus');
		}
	});

	jQuery(document).on('click', function(event) {
		if (!jQuery(event.target).closest($component).length) {
			closeDropdown();
		}
	});

	// Close the dropdown when the focus leaves the component with the keyboard (Tab). A click outside is managed by the click handler.
	$component.on('focusout', function(event) {
		if (event.relatedTarget && !jQuery.contains($component[0], event.relatedTarget)) {
			closeDropdown();
		}
	});

	// Expand fields that already have a selected variant
	refresh();
	$component.find('.customreportsmeasures-hasvariants').each(function() {
		if (jQuery(this).find('.customreportsmeasures-selected').length) {
			expandField(jQuery(this), true);
		}
	});
}

/**
 * Init a combo to select one field of custom reports (X axis, group by... HTML generated by customReportsSelectFieldCombo()).
 * Same principle than the combo of fields of the filter component: the main element is open with its fields,
 * the sub-elements are listed after the fields and are collapsed, a click on an element shows its content.
 *
 * @param	{string}	componentid		Id of the div of component
 * @return	{void}
 */
function initCustomReportsCombo(componentid)
{
	var $component = jQuery('#' + componentid);
	if (!$component.length || $component.data('initdone')) {
		return;
	}
	$component.data('initdone', 1);

	var $panel = $component.find('.customreportscombo-panel');
	var $search = $component.find('.customreportscombo-search');
	var $input = $component.children('input[type="hidden"]');

	/* Without search term, the root elements are open (fields and sub-elements shown), the deeper levels are closed
	 * except the elements containing the selected field */
	function showDefault()
	{
		$component.find('.customreportscombo-element').removeClass('open').show();
		$component.find('.customreportscombo-fields, .customreportscombo-children').hide();
		$component.find('.customreportscombo-field').show();
		$component.find('.customreportscombo-list > .customreportscombo-element').addClass('open').children('.customreportscombo-fields, .customreportscombo-children').show();
		$component.find('.customreportscombo-field.selected').parents('.customreportscombo-element').addClass('open').children('.customreportscombo-fields, .customreportscombo-children').show();
	}

	// Click on the toggle button: show/hide the panel
	$component.find('.customreportscombo-toggle').on('click', function(e) {
		if (jQuery(e.target).closest('.customreportscombo-clear').length) {
			return;	// Managed by the handler of the clear button
		}
		e.stopPropagation();
		$panel.toggle();
		$search.val('');
		showDefault();
		if ($panel.is(':visible')) {
			$search.trigger('focus');
		}
	});

	// Click on the clear button: unselect the field
	$component.on('click', '.customreportscombo-clear', function(e) {
		e.stopPropagation();
		var $label = $component.find('.customreportscombo-label');
		$component.find('.customreportscombo-field').removeClass('selected');
		$label.text($label.attr('data-placeholder')).addClass('opacitymedium').removeAttr('title');
		jQuery(this).addClass('hideobject');
		$input.val('').trigger('change');
		$panel.hide();
	});

	// Click on an element: show its fields and sub-elements. Other elements are closed, except the parents of the clicked one.
	$component.on('click', '.customreportscombo-elementheader', function(e) {
		e.stopPropagation();
		var $element = jQuery(this).closest('.customreportscombo-element');
		var wasopen = $element.hasClass('open');
		$component.find('.customreportscombo-element').removeClass('open');
		$component.find('.customreportscombo-fields, .customreportscombo-children').hide();
		$component.find('.customreportscombo-field').show();
		$element.parents('.customreportscombo-element').addClass('open').show().children('.customreportscombo-fields, .customreportscombo-children').show();
		if (!wasopen) {
			$element.addClass('open').show().children('.customreportscombo-fields, .customreportscombo-children').show();
		}
	});

	// Click on a field: select it and close the panel
	$component.on('click', '.customreportscombo-field', function(e) {
		e.stopPropagation();
		var fieldlabel = jQuery(this).text();
		var elementlabelhtml = jQuery(this).closest('.customreportscombo-element').find('.customreportscombo-elementlabel').first().html();
		$component.find('.customreportscombo-field').removeClass('selected');
		jQuery(this).addClass('selected');
		var $label = $component.find('.customreportscombo-label');
		$label.html(elementlabelhtml).removeClass('opacitymedium').append(document.createTextNode(': ' + fieldlabel));
		$label.attr('title', $label.text().trim());	// Full label as tooltip, as the label may be truncated
		$input.val(jQuery(this).attr('data-field')).trigger('change');
		$component.find('.customreportscombo-clear').removeClass('hideobject');
		$component.find('.customreportscombo-toggle').trigger('focus');	// The selected row is now hidden, keep the focus on the combo
		$panel.hide();
	});

	// Type something into the search input to filter the list of elements and fields
	$search.on('keyup change', function() {
		var term = jQuery(this).val().toLowerCase();
		if (term === '') {
			showDefault();
			return;
		}
		$component.find('.customreportscombo-element').each(function() {
			var elementmatch = jQuery(this).children('.customreportscombo-elementheader').find('.customreportscombo-elementlabel').text().toLowerCase().indexOf(term) > -1;
			var hasfieldmatch = false;
			jQuery(this).children('.customreportscombo-fields').children('.customreportscombo-field').each(function() {
				var fieldmatch = elementmatch || jQuery(this).text().toLowerCase().indexOf(term) > -1;
				jQuery(this).toggle(fieldmatch);
				hasfieldmatch = hasfieldmatch || fieldmatch;
			});
			jQuery(this).toggleClass('open', elementmatch || hasfieldmatch);
			jQuery(this).children('.customreportscombo-fields').toggle(elementmatch || hasfieldmatch);
		});
		$component.find('.customreportscombo-element').each(function() {
			if (jQuery(this).hasClass('open')) {
				jQuery(this).show();
				jQuery(this).parents('.customreportscombo-element').addClass('open').show().children('.customreportscombo-children').show();
			} else {
				jQuery(this).hide();
			}
		});
	});

	// Down or right arrow on the toggle button opens the panel (Space and Enter already click the button)
	$component.find('.customreportscombo-toggle').on('keydown', function(e) {
		if ((e.key === 'ArrowDown' || e.key === 'ArrowRight') && !$panel.is(':visible')) {
			e.preventDefault();
			jQuery(this).trigger('click');
		}
	});

	// Up and down arrows into the panel move on the previous or next visible row
	$panel.on('keydown', function(e) {
		customReportsMoveFocusInList(e, $component.find('.customreportscombo-elementheader:visible, .customreportscombo-field:visible'), $search);
	});

	// Escape closes the panel, Enter on a row activates it
	$component.on('keydown', function(e) {
		if (e.which === 27) {
			if ($panel.is(':visible')) {
				$component.find('.customreportscombo-toggle').trigger('focus');	// Keep the focus visible on the combo
			}
			$panel.hide();
		}
	});
	$search.on('keydown', function(e) {
		if (e.which === 13) {
			e.preventDefault();	// Do not submit the form
		}
	});
	$component.on('keydown', '.customreportscombo-elementheader, .customreportscombo-field', function(e) {
		if (e.which === 13) {
			e.preventDefault();
			jQuery(this).trigger('click');
		}
	});

	// Close the panel when we click outside of it
	jQuery(document).on('click', function(e) {
		if (!jQuery(e.target).closest($component).length) {
			$panel.hide();
		}
	});

	// Close the panel when the focus leaves the component with the keyboard (Tab). A click outside is managed by the click handler.
	$component.on('focusout', function(e) {
		if (e.relatedTarget && !jQuery.contains($component[0], e.relatedTarget)) {
			$panel.hide();
		}
	});
}
