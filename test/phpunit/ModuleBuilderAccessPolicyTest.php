/**
 * Class ModuleBuilderAccessPolicyTest
 *
 * @backupGlobals disabled
 * @backupStaticAttributes enabled
 * @remarks	backupGlobals must be disabled to have db,conf,user and lang not erased.
 * @phan-file-suppress PhanUndeclaredExtendedClass
 * @phan-file-suppress PhanUndeclaredClass
 * @phan-file-suppress PhanUndeclaredMethod
 */
class ModuleBuilderAccessPolicyTest extends CommonClassTest
{
	/**
	 * @var array<string,mixed> Value of $conf->modules['mymodule'] before the test, null when unset
	 */
	private $savedModuleState = array();

	/**
	 * Declare the fake 'mymodule' module enabled, as User::hasRight() returns 0 for a disabled module.
	 *
	 * @return void
	 */
	protected function setUp(): void
	{
		global $conf;

		parent::setUp();
		$this->savedModuleState = array('mymodule' => isset($conf->modules['mymodule']) ? $conf->modules['mymodule'] : null);
		$conf->modules['mymodule'] = 'mymodule';
	}

	/**
	 * @return void
	 */
	protected function tearDown(): void
	{
		global $conf;

		if ($this->savedModuleState['mymodule'] === null) {
			unset($conf->modules['mymodule']);
		} else {
			$conf->modules['mymodule'] = $this->savedModuleState['mymodule'];
		}
		parent::tearDown();
	}

	/**
	 * Build a user profile with the given characteristics and rights on the fake object.
	 *
	 * @param	int			$admin	1 if the user is an administrator
	 * @param	int			$socid	Id of the thirdparty of an external user, 0 for an internal user
	 * @param	string[]	$rights	Rights granted on mymodule/myobject (read, write, delete)
	 * @return	User
	 */
	private function buildUser($admin, $socid, $rights)
	{
		global $db;

		$profile = new User($db);
		$profile->admin = $admin;
		$profile->socid = $socid;
		$profile->rights = new stdClass();
		$profile->rights->mymodule = new stdClass();
		$profile->rights->mymodule->myobject = new stdClass();
		foreach ($rights as $right) {
			$profile->rights->mymodule->myobject->$right = 1;
		}
		return $profile;
	}

	/**
	 * Return the profiles used by the truth tables.
	 *
	 * @return array<string,User>
	 */
	private function getProfiles()
	{
		return array(
			'admin without right' => $this->buildUser(1, 0, array()),
			'internal reader'     => $this->buildUser(0, 0, array('read')),
			'external reader'     => $this->buildUser(0, 12, array('read')),
			'internal without right' => $this->buildUser(0, 0, array()),
		);
	}

	/**
	 * Return an object carrying the module and element of the generated object.
	 *
	 * @return CommonObject
	 */
	private function buildObject()
	{
		global $db;

		return new class ($db) extends CommonObject {
			/** @var string */
			public $module = 'mymodule';
			/** @var string */
			public $element = 'myobject';

			/**
			 * @param	DoliDB	$db	Database handler
			 */
			public function __construct($db)
			{
				$this->db = $db;
			}
		};
	}

	/**
	 * Policy (isAdmin OR canReadObject), the example of the specification.
	 *
	 * @return AccessPolicyConfig
	 */
	private function buildAdminOrReaderPolicy()
	{
		return new AccessPolicyConfig(new OrRule(array(
			new PredicateRule(PredicateRule::IS_ADMIN),
			new PredicateRule(PredicateRule::CAN_READ_OBJECT),
		)));
	}

	/**
	 * Policy (canReadObject AND isInternalUser).
	 *
	 * @return AccessPolicyConfig
	 */
	private function buildInternalReaderPolicy()
	{
		return new AccessPolicyConfig(new AndRule(array(
			new PredicateRule(PredicateRule::CAN_READ_OBJECT),
			new PredicateRule(PredicateRule::IS_INTERNAL_USER),
		)));
	}

	/**
	 * @return void
	 */
	public function testPredicateRuleRejectsUnknownName()
	{
		$this->expectException(InvalidArgumentException::class);
		new PredicateRule('isSuperUser');
	}

	/**
	 * @return void
	 */
	public function testPredicateRuleRendersWhitelistedCode()
	{
		$this->assertSame('!empty($user->admin)', (new PredicateRule(PredicateRule::IS_ADMIN))->toPhp());
		$this->assertSame('empty($user->socid)', (new PredicateRule(PredicateRule::IS_INTERNAL_USER))->toPhp());
		$this->assertSame("\$user->hasRight('mymodule', 'myobject', 'read')", (new PredicateRule(PredicateRule::CAN_READ_OBJECT))->toPhp());
		$this->assertSame("\$user->hasRight('mymodule', 'myobject', 'write')", (new PredicateRule(PredicateRule::CAN_WRITE_OBJECT))->toPhp());
		$this->assertSame("\$user->hasRight('mymodule', 'myobject', 'delete')", (new PredicateRule(PredicateRule::CAN_DELETE_OBJECT))->toPhp());
	}

	/**
	 * @return void
	 */
	public function testCompositeRuleRejectsEmptyList()
	{
		$this->expectException(InvalidArgumentException::class);
		new OrRule(array());
	}

	/**
	 * @return void
	 */
	public function testCompositeRuleRejectsNonExpressionChild()
	{
		$this->expectException(InvalidArgumentException::class);
		new AndRule(array('isAdmin'));
	}

	/**
	 * OR must be rendered with || inside explicit parentheses: the `or` keyword binds looser than `=`.
	 *
	 * @return void
	 */
	public function testCompositeRulesRenderExplicitParentheses()
	{
		$rule = new OrRule(array(
			new PredicateRule(PredicateRule::IS_ADMIN),
			new AndRule(array(
				new PredicateRule(PredicateRule::CAN_READ_OBJECT),
				new PredicateRule(PredicateRule::IS_INTERNAL_USER),
			)),
		));

		$this->assertSame("(!empty(\$user->admin) || (\$user->hasRight('mymodule', 'myobject', 'read') && empty(\$user->socid)))", $rule->toPhp());
		$this->assertDoesNotMatchRegularExpression('/\b(and|or)\b/i', $rule->toPhp());
	}

	/**
	 * @return void
	 */
	public function testPolicySerializationRoundTrip()
	{
		$policy = new AccessPolicyConfig(new OrRule(array(
			new PredicateRule(PredicateRule::IS_ADMIN),
			new AndRule(array(new PredicateRule(PredicateRule::CAN_READ_OBJECT), new PredicateRule(PredicateRule::IS_INTERNAL_USER))),
		)), 'ErrorForbidden');

		$json = $policy->toJson();
		$this->assertSame('{"expression":{"type":"or","rules":[{"type":"predicate","name":"isAdmin"},{"type":"and","rules":[{"type":"predicate","name":"canReadObject"},{"type":"predicate","name":"isInternalUser"}]}]},"message":"ErrorForbidden"}', $json);

		$restored = AccessPolicyConfig::fromJson($json);
		$this->assertSame($json, $restored->toJson());
		$this->assertSame($policy->getExpression()->toPhp(), $restored->getExpression()->toPhp());
		$this->assertSame('ErrorForbidden', $restored->getMessage());
	}

	/**
	 * @return array<string,array{0:string}>
	 */
	public function provideInvalidSerializedPolicies()
	{
		return array(
			'not json'          => array('{"expression":'),
			'not an object'     => array('"isAdmin"'),
			'no expression'     => array('{"message":""}'),
			'unknown type'      => array('{"expression":{"type":"not","rules":[{"type":"predicate","name":"isAdmin"}]}}'),
			'unknown predicate' => array('{"expression":{"type":"predicate","name":"isRoot"}}'),
			'predicate no name' => array('{"expression":{"type":"predicate"}}'),
			'empty rules'       => array('{"expression":{"type":"or","rules":[]}}'),
			'rules not a list'  => array('{"expression":{"type":"or","rules":"isAdmin"}}'),
			'bad message'       => array('{"expression":{"type":"predicate","name":"isAdmin"},"message":"<b>x</b>"}'),
			'message not text'  => array('{"expression":{"type":"predicate","name":"isAdmin"},"message":["x"]}'),
			'message with eol'  => array('{"expression":{"type":"predicate","name":"isAdmin"},"message":"ErrorForbidden\\n"}'),
			'too deep'          => array('{"expression":{"type":"or","rules":[{"type":"and","rules":[{"type":"or","rules":[{"type":"and","rules":[{"type":"or","rules":[{"type":"predicate","name":"isAdmin"}]}]}]}]}]}}'),
		);
	}

	/**
	 * A forged serialized policy must be rejected, never partially loaded.
	 *
	 * @dataProvider provideInvalidSerializedPolicies
	 * @param	string	$json	Serialized policy
	 * @return	void
	 */
	public function testPolicyRejectsInvalidSerialization($json)
	{
		$this->expectException(InvalidArgumentException::class);
		AccessPolicyConfig::fromJson($json);
	}

	/**
	 * @return void
	 */
	public function testPolicyRejectsTooManyNodes()
	{
		$rules = array();
		for ($i = 0; $i <= AccessPolicyConfig::MAX_NODES; $i++) {
			$rules[] = new PredicateRule(PredicateRule::IS_ADMIN);
		}

		$this->expectException(InvalidArgumentException::class);
		new AccessPolicyConfig(new OrRule($rules));
	}

	/**
	 * @return void
	 */
	public function testFromAlternativesReturnsNullWhenNothingIsChecked()
	{
		$this->assertNull(AccessPolicyConfig::fromAlternatives(array(array(), array(), array())));
		$this->assertNull(AccessPolicyConfig::fromAlternatives(array()));
	}

	/**
	 * A single predicate or a single alternative must not be wrapped in a useless composite node.
	 *
	 * @return void
	 */
	public function testFromAlternativesBuildsTheSmallestTree()
	{
		$single = AccessPolicyConfig::fromAlternatives(array(array(), array('canReadObject')));
		$this->assertInstanceOf(PredicateRule::class, $single->getExpression());

		$conjunction = AccessPolicyConfig::fromAlternatives(array(array('canReadObject', 'isInternalUser')));
		$this->assertInstanceOf(AndRule::class, $conjunction->getExpression());

		$policy = AccessPolicyConfig::fromAlternatives(array(array('isAdmin'), array('canReadObject', 'isInternalUser')), 'ErrorForbidden');
		$this->assertSame("(!empty(\$user->admin) || (\$user->hasRight('mymodule', 'myobject', 'read') && empty(\$user->socid)))", $policy->getExpression()->toPhp());
		$this->assertSame('ErrorForbidden', $policy->getMessage());
	}

	/**
	 * Filtering an unknown predicate out of an AND group would widen the access: it must be rejected.
	 *
	 * @return void
	 */
	public function testFromAlternativesRejectsUnknownPredicate()
	{
		$this->expectException(InvalidArgumentException::class);
		AccessPolicyConfig::fromAlternatives(array(array('canReadObject', 'isInternalUserForged')));
	}

	/**
	 * @return void
	 */
	public function testFromAlternativesRejectsNestedValues()
	{
		$this->expectException(InvalidArgumentException::class);
		AccessPolicyConfig::fromAlternatives(array(array(array('isAdmin'))));
	}

	/**
	 * @return void
	 */
	public function testFromAlternativesRejectsTooManyAlternatives()
	{
		$alternatives = array_fill(0, AccessPolicyConfig::MAX_ALTERNATIVES + 1, array('isAdmin'));

		$this->expectException(InvalidArgumentException::class);
		AccessPolicyConfig::fromAlternatives($alternatives);
	}

	/**
	 * @return array<string,array{0:string,1:array<string,bool>}>
	 */
	public function providePolicyTruthTables()
	{
		return array(
			'isAdmin OR canReadObject' => array('buildAdminOrReaderPolicy', array(
				'admin without right' => true,
				'internal reader' => true,
				'external reader' => true,
				'internal without right' => false,
			)),
			'canReadObject AND isInternalUser' => array('buildInternalReaderPolicy', array(
				'admin without right' => false,
				'internal reader' => true,
				'external reader' => false,
				'internal without right' => false,
			)),
		);
	}

	/**
	 * @dataProvider providePolicyTruthTables
	 * @param	string				$builder	Name of the method building the policy
	 * @param	array<string,bool>	$expected	Expected access, by profile
	 * @return	void
	 */
	public function testEvaluatorGrantsAccessByProfile($builder, $expected)
	{
		$evaluator = new AccessPolicyEvaluator($this->$builder());
		$object = $this->buildObject();

		foreach ($this->getProfiles() as $label => $profile) {
			$this->assertSame($expected[$label], $evaluator->evaluate($profile, $object), 'Wrong access for profile '.$label);
		}
	}

	/**
	 * The page block generated from a policy must grant exactly the same access as the evaluator.
	 *
	 * @dataProvider providePolicyTruthTables
	 * @param	string				$builder	Name of the method building the policy
	 * @param	array<string,bool>	$expected	Expected access, by profile
	 * @return	void
	 */
	public function testGeneratedBlockMatchesEvaluator($builder, $expected)
	{
		$policy = $this->$builder();
		$evaluator = new AccessPolicyEvaluator($policy);
		$object = $this->buildObject();
		$check = $this->compileGeneratedBlock(renderModuleBuilderAccessPolicyBlock($policy));

		foreach ($this->getProfiles() as $label => $profile) {
			$this->assertSame($expected[$label], (bool) $check($profile), 'Generated block gives a wrong access for profile '.$label);
			$this->assertSame($evaluator->evaluate($profile, $object), (bool) $check($profile), 'Generated block and evaluator disagree for profile '.$label);
		}
	}

	/**
	 * A failure while evaluating the generated block must deny the access.
	 *
	 * @return void
	 */
	public function testGeneratedBlockDeniesOnFailure()
	{
		$check = $this->compileGeneratedBlock(renderModuleBuilderAccessPolicyBlock($this->buildInternalReaderPolicy()));

		$this->assertFalse($check(null));
	}

	/**
	 * A failure while evaluating the policy must deny the access and leave a technical log line.
	 *
	 * @return void
	 */
	public function testEvaluatorDeniesAndLogsOnFailure()
	{
		global $conf, $db;

		$failing = new class ($db) extends User {
			/**
			 * @param	string		$module			Module
			 * @param	string		$permlevel1		Permission level 1
			 * @param	string		$permlevel2		Permission level 2
			 * @return	int
			 * @throws	RuntimeException
			 */
			public function hasRight($module, $permlevel1, $permlevel2 = '')
			{
				throw new RuntimeException('rights not loaded');
			}
		};

		$saved = array(
			'syslog' => isset($conf->modules['syslog']) ? $conf->modules['syslog'] : null,
			'MAIN_ENABLE_LOG_TO_HTML' => getDolGlobalString('MAIN_ENABLE_LOG_TO_HTML'),
			'SYSLOG_LEVEL' => getDolGlobalString('SYSLOG_LEVEL'),
			'logtohtml' => isset($_REQUEST['logtohtml']) ? $_REQUEST['logtohtml'] : null,
		);
		$conf->modules['syslog'] = 'syslog';
		$conf->global->MAIN_ENABLE_LOG_TO_HTML = 1;
		$conf->global->SYSLOG_LEVEL = LOG_DEBUG;
		$_REQUEST['logtohtml'] = 1;
		$conf->logbuffer = array();

		try {
			$granted = (new AccessPolicyEvaluator($this->buildAdminOrReaderPolicy()))->evaluate($failing, $this->buildObject());
			$logged = implode("\n", $conf->logbuffer);
		} finally {
			if ($saved['syslog'] === null) {
				unset($conf->modules['syslog']);
			} else {
				$conf->modules['syslog'] = $saved['syslog'];
			}
			$conf->global->MAIN_ENABLE_LOG_TO_HTML = $saved['MAIN_ENABLE_LOG_TO_HTML'];
			$conf->global->SYSLOG_LEVEL = $saved['SYSLOG_LEVEL'];
			if ($saved['logtohtml'] === null) {
				unset($_REQUEST['logtohtml']);
			} else {
				$_REQUEST['logtohtml'] = $saved['logtohtml'];
			}
		}

		$this->assertFalse($granted);
		$this->assertStringContainsString('rights not loaded', $logged);
	}

	/**
	 * Turn a generated page block into a callable returning the computed $permissiontoread.
	 *
	 * @param	string	$block	PHP block, as written into a generated page
	 * @return	callable(User|null):mixed
	 */
	private function compileGeneratedBlock($block)
	{
		$basefile = tempnam(sys_get_temp_dir(), 'mbaccesspolicy');
		$tmpfile = $basefile.'.php';
		file_put_contents($tmpfile, "<?php\nreturn function (\$user) {\n\$permissiontoread = 1;\n".$block."return \$permissiontoread;\n};\n");
		$check = include $tmpfile;
		unlink($tmpfile);
		unlink($basefile);

		return $check;
	}
}
